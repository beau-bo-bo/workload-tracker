-- 0006_drop_legacy_owner_inspector_columns.sql
--
-- ลบคอลัมน์ tasks.owner / tasks.inspector (text) ที่เก็บ "ชื่อคน" แบบเดิมทิ้ง
-- ถูกแทนที่ด้วย owner_id / inspector_id ใน 0005 เรียบร้อยแล้ว และไม่มีโค้ดหรือฟังก์ชันไหนอ่านอีก
--
-- ผู้ใช้ยืนยันให้ลบเมื่อ 2026-09-15 (ยังเป็นข้อมูลทดสอบ ไม่ใช่ข้อมูลงานจริง)
--
-- ตรวจก่อนลบทั้ง 4 ข้อ ผ่านหมด:
--   1. ไม่มีแถวที่มีชื่อเดิมแต่ไม่มี id          → 0 แถว
--   2. ชื่อที่เก็บไว้ตรงกับชื่อปัจจุบันของเจ้าของ id → ไม่มีแถวที่ชี้ผิดคน
--   3. ไม่มีฟังก์ชันใน public ที่อ้างถึงคอลัมน์นี้
--   4. ไม่มีโค้ดฝั่งเว็บอ่าน row.owner / row.inspector
--
-- ⚠️ ลบคอลัมน์ย้อนกลับไม่ได้ — ถ้าต้องกู้ ต้องใช้ Point-in-Time Recovery ของ Supabase

alter table public.tasks
  drop column owner,
  drop column inspector;
